// Generates web/src/worldmap.js: a compact, offline land outline of the world (110m Natural Earth
// via the world-atlas package) as one SVG path in an equirectangular 360 x 180 box
// (x = lon + 180, y = 90 - lat). Run:  cd tools && npm install && node make-worldmap.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

const r1 = (n) => Math.round(n * 10) / 10;
let d = '';
const polys = land.type === 'FeatureCollection' ? land.features.map((f) => f.geometry) : [land.geometry || land];
for (const g of polys) {
  const rings = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of rings) {
    for (const ring of poly) {
      let last = null;
      const pts = [];
      for (const [lon, lat] of ring) {
        const p = [r1(lon + 180), r1(90 - lat)];
        if (last && last[0] === p[0] && last[1] === p[1]) continue;
        pts.push(p); last = p;
      }
      if (pts.length < 3) continue;
      d += 'M' + pts.map((p) => p.join(' ')).join('L') + 'Z';
    }
  }
}
const out = `// Generated by tools/make-worldmap.mjs from Natural Earth 110m land (public domain). Do not edit.
// Equirectangular outline: x = lon + 180, y = 90 - lat (viewBox 0 0 360 180).
export const MAP_LAT_TOP = 80;
export const MAP_LAT_BOTTOM = -58;
export const LAND_PATH = '${d}';
`;
writeFileSync(new URL('../web/src/worldmap.js', import.meta.url), out);
console.log('worldmap.js written,', out.length, 'bytes');
